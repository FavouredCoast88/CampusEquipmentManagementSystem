    private void loadEquipmentTable(){
        DefaultTableModel model = (DefaultTableModel) tblEquipment.getModel();
        model.setRowCount(0);
        
        try{
            ArrayList<Equipment> equipmentList = equipmentDAO.getAllEquipment();
            
            for(Equipment equipment : equipmentList){
                model.addRow(new Object[]{
                    equipment.getEquipmentID(),
                    equipment.getEquipmentName(),
                    equipment.getCategory(),
                    equipment.getConditionStatus(),
                    equipment.getQuantity(),
                    equipment.isAvailable()
                });
            }//end for
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this, "Could not load equipment: " + e.getMessage(), "Database Error", JOptionPane.ERROR_MESSAGE);
        }//end catch
    }//end loadEquipmentTable
    
    private void fillFormFromTable(){
        int selectedRow = tblEquipment.getSelectedRow();
        
        if(selectedRow == -1){
            return;
        }//end if
        
        txtEquipmentID.setText(tblEquipment.getValueAt(selectedRow, 0).toString());
        txtEquipmentName.setText(tblEquipment.getValueAt(selectedRow, 1).toString());
        txtCategory.setText(tblEquipment.getValueAt(selectedRow, 2).toString());
        cmbConditionStatus.setSelectedItem(tblEquipment.getValueAt(selectedRow, 3).toString());
        txtQuantity.setText(tblEquipment.getValueAt(selectedRow, 4).toString());
        boolean available = Boolean.parseBoolean(tblEquipment.getValueAt(selectedRow, 5).toString());
        chkAvailable.setSelected(available);       
    }//end fillFormFromTable method
    
    private void ClearFields(){
        txtEquipmentID.setText("");
        txtEquipmentName.setText("");
        txtCategory.setText("");
        txtQuantity.setText("");
        cmbConditionStatus.setSelectedIndex(0);
        chkAvailable.setSelected(false);
        tblEquipment.clearSelection();
    }//end ClearFields method

