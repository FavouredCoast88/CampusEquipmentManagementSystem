    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        
        try{
            String name = txtEquipmentName.getText().trim();
            String category = txtCategory.getText().trim();
            String condition = cmbConditionStatus.getSelectedItem().toString();
            int quantity = Integer.parseInt(txtQuantity.getText().trim());
            boolean available = chkAvailable.isSelected();
            
            Equipment equipment = new Equipment(0, name, category, condition, quantity, available);
            equipmentDAO.addEquipment(equipment);
            
            JOptionPane.showMessageDialog(this, "Equipment added successfully!");
            loadEquipmentTable();
        }catch(NumberFormatException e){
            JOptionPane.showMessageDialog(this, "Quantity must be a valid number.","Invalid Input",JOptionPane.ERROR_MESSAGE);
        }catch(SQLException e){
            JOptionPane.showMessageDialog(this,"Database error: " + e.getMessage(), "Database Error",JOptionPane.ERROR_MESSAGE);
        }//end catch
     //end add button   
    }//GEN-LAST:event_btnAddActionPerformed

